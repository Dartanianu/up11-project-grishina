CREATE TABLE IF NOT EXISTS product_variation (
    variation_id SERIAL PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS manufactures (
    manufacture_id SERIAL PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS categories (
    category_id SERIAL PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS subcategories (
    subcategory_id SERIAL PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE roles (
    role_id SERIAL PRIMARY KEY,
    name VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
    user_id SERIAL PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    second_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50),
    login VARCHAR(50) NOT NULL UNIQUE,
    role_id INTEGER REFERENCES roles(role_id)
);

CREATE TABLE IF NOT EXISTS orders (
    order_id SERIAL PRIMARY KEY,
    order_date DATE DEFAULT CURRENT_DATE,
    user_id INTEGER REFERENCES users(user_id)
);

CREATE TABLE IF NOT EXISTS products (
    product_id SERIAL PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    compound TEXT,
    price NUMERIC(10,2) NOT NULL,
    image_path VARCHAR(50),
    manufacture_id INTEGER REFERENCES manufactures(manufacture_id),
    category_id INTEGER REFERENCES categories(category_id),
    subcategory_id INTEGER REFERENCES subcategories(subcategory_id)
);

CREATE TABLE IF NOT EXISTS stock_items (
    stok_item_id SERIAL PRIMARY KEY,
    product_id INTEGER REFERENCES products(product_id),
    variation_id INTEGER REFERENCES product_variation(variation_id),
    quantity INTEGER CHECK(quantity>=0)
);

CREATE TABLE IF NOT EXISTS order_items (
    order_item_id SERIAL PRIMARY KEY,
    order_id INTEGER REFERENCES orders(order_id),
    product_id INTEGER REFERENCES products(product_id),
    variation_id INTEGER REFERENCES product_variation(variation_id),
    quantity INTEGER NOT NULL DEFAULT(1),
    price NUMERIC(10,2)
);

